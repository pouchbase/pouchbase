import type { RouteMethod } from '../server.js';

import { resolve, sep } from 'node:path';
import { rolldown, type Plugin } from 'rolldown';

import { ProjectError } from './project-error.js';

/**
 * The server code of a plugin: the entry module that the CLI generates from the project layout,
 * bundling it into one ES module without imports, and loading that module in Node.js to read
 * what it exports.
 */

/** The HTTP methods a file in `routes/` can export, in the order the CLI lists them. */
export const ROUTE_METHODS = [
	'GET',
	'POST',
	'PUT',
	'PATCH',
	'DELETE'
] as const satisfies readonly RouteMethod[];

/** Id of the generated server entry, for a bundler's `resolveId` and `load` hooks. */
export const SERVER_ENTRY_ID = 'virtual:pouchbase-plugin/server';

/** What the generated server entry imports: project files by their path in the project. */
export type ServerEntryInput = {
	/** `{ type: 'rating', file: 'fields/rating/field.ts' }`: default-exports `defineField(...)`. */
	fields: readonly { type: string; file: string }[];
	/** `{ id: 'gitlab', file: 'auth/gitlab/provider.ts' }`: default-exports `defineAuthProvider(...)`. */
	authProviders: readonly { id: string; file: string }[];
	/**
	 * `{ path: '/items/:id', file: 'routes/items/[id].ts' }`: exports `GET`, `POST`, ... With
	 * `methods`, the entry has a literal key per method (`"GET /items/:id": route0.GET`); without,
	 * it finds the methods when it runs.
	 */
	routes: readonly { path: string; file: string; methods?: readonly RouteMethod[] }[];
	/** `plugin.ts`: default-exports `definePlugin({ settings })`; its settings join the entry. */
	plugin?: string | null;
};

export type ServerEntryOptions = {
	/**
	 * The plugin's directory. The entry imports the files by their absolute path in it, with forward
	 * slashes (`C:/plugins/demo/fields/rating/field.ts`); without it, by `./<path>`.
	 */
	root?: string;
	/** Turns a project path into the specifier the entry imports; overrides `root`. */
	specifier?: (file: string) => string;
};

function toPosix(path: string) {
	return path.split(sep).join('/');
}

/**
 * The source of the server entry for a plugin in the convention layout: it imports every field
 * type, auth provider and route file (and `plugin.ts`) and default-exports
 * `{ settings, fields, authProviders, routes }`, the same object `definePlugin(...)` takes. A route file contributes a key for every method it exports
 * as a function (`GET /items/:id`): the given `methods`, else those it finds when it runs. The
 * source has no other imports, so a bundler only needs to resolve the project files.
 */
export function generateServerEntry(
	input: ServerEntryInput,
	options: ServerEntryOptions = {}
): string {
	const specifier =
		options.specifier ??
		((file: string) => (options.root ? toPosix(resolve(options.root, file)) : `./${file}`));
	const imports: string[] = [];
	const fields: string[] = [];
	const providers: string[] = [];
	const routes: string[] = [];
	const literalRoutes: string[] = [];

	if (input.plugin) {
		imports.push(`import plugin from ${JSON.stringify(specifier(input.plugin))};`);
	}

	input.fields.forEach(({ type, file }, index) => {
		imports.push(`import field${index} from ${JSON.stringify(specifier(file))};`);
		fields.push(`\t\t${JSON.stringify(type)}: field${index}`);
	});

	input.authProviders.forEach(({ id, file }, index) => {
		imports.push(`import provider${index} from ${JSON.stringify(specifier(file))};`);
		providers.push(`\t\t${JSON.stringify(id)}: provider${index}`);
	});

	input.routes.forEach(({ path, file, methods }, index) => {
		imports.push(`import * as route${index} from ${JSON.stringify(specifier(file))};`);

		if (methods) {
			for (const method of methods) {
				literalRoutes.push(`\t\t${JSON.stringify(`${method} ${path}`)}: route${index}.${method}`);
			}
		} else {
			routes.push(`\t\t\t[${JSON.stringify(path)}, route${index}]`);
		}
	});

	const entries = routes.length
		? [...literalRoutes, `\t\t...routes([\n${routes.join(',\n')}\n\t\t])`]
		: literalRoutes;
	const helper = routes.length
		? `
const METHODS = ${JSON.stringify(ROUTE_METHODS)};

/** Route keys such as "GET /items/:id" for every method a route file exports. */
function routes(files) {
	const result = {};

	for (const [path, module] of files) {
		for (const method of METHODS) {
			if (typeof module[method] === 'function') {
				result[method + ' ' + path] = module[method];
			}
		}
	}

	return result;
}
`
		: '';

	return `// Generated by pouchbase-plugin from the project layout.
${imports.join('\n')}
${helper}
export default {${input.plugin ? '\n\tsettings: plugin?.settings ?? [],' : ''}
	fields: {
${fields.join(',\n')}
	},
	authProviders: {
${providers.join(',\n')}
	},
	routes: {
${entries.join(',\n')}
	}
};
`;
}

/** Serves `source` as the module `SERVER_ENTRY_ID`. */
function virtualEntry(source: string): Plugin {
	const resolved = `\0${SERVER_ENTRY_ID}`;

	return {
		name: 'pouchbase-plugin-server-entry',
		resolveId(id) {
			return id === SERVER_ENTRY_ID ? resolved : null;
		},
		load(id) {
			return id === resolved ? source : null;
		}
	};
}

/**
 * The server code bundled into one ES module without imports: from a file of the project
 * (`{ file: 'server/index.ts' }`) or from generated source (`{ source }`). `label` names it in
 * errors.
 */
export async function bundleServerCode(
	root: string,
	entry: { file: string } | { source: string },
	label = 'file' in entry ? entry.file : 'the server code'
): Promise<string> {
	let code: string;
	let imports: string[];

	try {
		const build = await rolldown({
			input: 'file' in entry ? resolve(root, entry.file) : SERVER_ENTRY_ID,
			cwd: resolve(root),
			platform: 'neutral',
			logLevel: 'silent',
			plugins: 'source' in entry ? [virtualEntry(entry.source)] : []
		});
		const { output } = await build.generate({ format: 'esm', minify: true });
		await build.close();

		code = output[0].code;
		imports = [...output[0].imports, ...output[0].dynamicImports];
	} catch (error) {
		throw new ProjectError(`Can't bundle ${label}: ${(error as Error).message}`);
	}

	if (imports.length) {
		const packages = imports.filter((name) => !name.startsWith('node:'));

		throw new ProjectError(
			`The server code imports ${imports.join(', ')}; it runs in a sandbox without Node.js or other modules`,
			[],
			packages.length
				? `Packages are bundled into the server code, so they must be installed: run your package manager's install, or remove the import of ${packages.join(', ')}.`
				: 'Use the APIs of the sandbox (fetch, crypto, ctx) instead of Node.js modules.'
		);
	}

	return code;
}

/** Runs bundled server code in Node.js (as a `data:` URL module) and returns its default export. */
export async function importServerCode(code: string): Promise<unknown> {
	const url = `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
	const loaded = (await import(/* @vite-ignore */ url)) as { default?: unknown };

	return loaded.default;
}
