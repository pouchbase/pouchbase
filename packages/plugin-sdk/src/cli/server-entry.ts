import type { RouteMethod } from '../server.js';

import { resolve, sep } from 'node:path';
import { rolldown, type Plugin } from 'rolldown';

import { pluginFiles } from '../vite.js';
import { ProjectError } from './project-error.js';

/**
 * The server code of a plugin: the entry module that the CLI generates for `plugin.ts`, bundling
 * it into one ES module without imports (with `.svelte` and `.svg` imports as `PluginFile`s, see
 * `vite.ts`), and loading that module in Node.js to read what it exports.
 */

/** The HTTP methods a route module can answer, in the order the CLI lists them. */
export const ROUTE_METHODS = [
	'GET',
	'POST',
	'PUT',
	'PATCH',
	'DELETE'
] as const satisfies readonly RouteMethod[];

/** Id of the generated server entry, for a bundler's `resolveId` and `load` hooks. */
export const SERVER_ENTRY_ID = 'virtual:pouchbase-plugin/server';

/** What the generated server entry imports. */
export type ServerEntryInput = {
	/** `plugin.ts`: default-exports `definePlugin({ ... })`. */
	plugin: string;
};

export type ServerEntryOptions = {
	/**
	 * The plugin's directory. The entry imports `plugin.ts` by its absolute path in it, with forward
	 * slashes (`C:/plugins/demo/plugin.ts`); without it, by `./plugin.ts`.
	 */
	root?: string;
	/** Turns a project path into the specifier the entry imports; overrides `root`. */
	specifier?: (file: string) => string;
};

function toPosix(path: string) {
	return path.split(sep).join('/');
}

/**
 * The source of the server entry: it imports `plugin.ts` and default-exports what the host runs (a
 * `ServerDefinition`): the settings, the field types and auth providers without their components
 * and icons, and a key per route and method (`"GET /items/:id"`) for every function a route module
 * has under a method's name. The source has no other imports, so a bundler only needs to resolve
 * the project files.
 */
export function generateServerEntry(
	input: ServerEntryInput,
	options: ServerEntryOptions = {}
): string {
	const specifier =
		options.specifier ??
		((file: string) => (options.root ? toPosix(resolve(options.root, file)) : `./${file}`));

	return `// Generated by pouchbase-plugin from ${input.plugin}.
import plugin from ${JSON.stringify(specifier(input.plugin))};

const METHODS = ${JSON.stringify(ROUTE_METHODS)};

/** \`record\` with each value's \`keys\` left out: the server code doesn't render anything. */
function without(record, keys) {
	const result = {};

	for (const [id, value] of Object.entries(record ?? {})) {
		const copy = { ...value };

		for (const key of keys) {
			delete copy[key];
		}

		result[id] = copy;
	}

	return result;
}

/** Route keys such as "GET /items/:id", for every method a route module answers. */
function routes(modules) {
	const result = {};

	for (const [path, module] of Object.entries(modules ?? {})) {
		for (const method of METHODS) {
			if (typeof module?.[method] === 'function') {
				result[method + ' ' + path] = module[method];
			}
		}
	}

	return result;
}

export default {
	settings: plugin?.settings ?? [],
	fields: without(plugin?.fields, ['input', 'preview', 'icon']),
	authProviders: without(plugin?.authProviders, ['icon']),
	routes: routes(plugin?.routes)
};
`;
}

/** Serves `source` as the module `SERVER_ENTRY_ID`. */
function virtualEntry(source: string): Plugin {
	const resolved = `\0${SERVER_ENTRY_ID}`;

	return {
		name: 'pouchbase-plugin-server-entry',
		resolveId(id) {
			return id === SERVER_ENTRY_ID ? resolved : null;
		},
		load(id) {
			return id === resolved ? source : null;
		}
	};
}

/**
 * The server code bundled into one ES module without imports: from a file of the project
 * (`{ file: 'server/index.ts' }`) or from generated source (`{ source }`). `label` names it in
 * errors.
 */
export async function bundleServerCode(
	root: string,
	entry: { file: string } | { source: string },
	label = 'file' in entry ? entry.file : 'the server code'
): Promise<string> {
	let code: string;
	let imports: string[];

	try {
		const build = await rolldown({
			input: 'file' in entry ? resolve(root, entry.file) : SERVER_ENTRY_ID,
			cwd: resolve(root),
			platform: 'neutral',
			logLevel: 'silent',
			plugins: [pluginFiles({ root }), ...('source' in entry ? [virtualEntry(entry.source)] : [])]
		});
		const { output } = await build.generate({ format: 'esm', minify: true });
		await build.close();

		code = output[0].code;
		imports = [...output[0].imports, ...output[0].dynamicImports];
	} catch (error) {
		throw new ProjectError(`Can't bundle ${label}: ${(error as Error).message}`);
	}

	if (imports.length) {
		const packages = imports.filter((name) => !name.startsWith('node:'));

		throw new ProjectError(
			`The server code imports ${imports.join(', ')}; it runs in a sandbox without Node.js or other modules`,
			[],
			packages.length
				? `Packages are bundled into the server code, so they must be installed: run your package manager's install, or remove the import of ${packages.join(', ')}.`
				: 'Use the APIs of the sandbox (fetch, crypto, ctx) instead of Node.js modules.'
		);
	}

	return code;
}

/** Runs bundled server code in Node.js (as a `data:` URL module) and returns its default export. */
export async function importServerCode(code: string): Promise<unknown> {
	const url = `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
	const loaded = (await import(/* @vite-ignore */ url)) as { default?: unknown };

	return loaded.default;
}
